@Composable
internal fun uiText(label: String): String = UI_LABELS[label]?.let { stringResource(it) } ?: label

internal fun Resources.uiLabel(label: String): String = UI_LABELS[label]?.let { getString(it) } ?: label

/** Resolve labels before entering the non-composable accessibility semantics lambda. */
@Composable
internal fun androidx.compose.ui.Modifier.uiDescription(label: String): androidx.compose.ui.Modifier {
    val description = uiText(label)
    return this.semantics { contentDescription = description }
}
